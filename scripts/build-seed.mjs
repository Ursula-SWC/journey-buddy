// Turns a timetable JSON file (the shape the prototype used) into SQL that loads it into D1.
// Usage: node scripts/build-seed.mjs <input.json> <output.sql>
//
// The output first clears the timetable tables, so it can be re-run safely.
// Images are left alone: stop photos are uploaded by staff, not seeded.

import { readFileSync, writeFileSync } from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error("Usage: node scripts/build-seed.mjs <input.json> <output.sql>");
  process.exit(1);
}

const data = JSON.parse(readFileSync(input, "utf8"));

const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`Bad number: ${v}`);
    return String(v);
  }
  if (typeof v === "boolean") return v ? "1" : "0";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (table, cols, vals) =>
  `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.map(q).join(", ")});`;
const pence = (pounds) => Math.round(Number(pounds) * 100);
const DAYS = new Set(["MF", "SA", "SU"]);
const checkDays = (d, where) => {
  if (!DAYS.has(d)) throw new Error(`Unknown day code "${d}" in ${where}`);
  return d;
};

const out = [
  "-- Generated by scripts/build-seed.mjs from " + input + ". Do not edit by hand.",
  "DELETE FROM busy_periods;",
  "DELETE FROM trips;",
  "DELETE FROM route_stops;",
  "DELETE FROM routes;",
  "DELETE FROM stop_notes;",
  "DELETE FROM stops;",
  "DELETE FROM meta;",
  "",
];

const meta = data.meta ?? {};
out.push(row("meta", ["key", "value"], ["sample", meta.sample ? "true" : "false"]));
if (meta.note) out.push(row("meta", ["key", "value"], ["note", meta.note]));
if (meta.updated) out.push(row("meta", ["key", "value"], ["updated", meta.updated]));
if (meta.helpline?.name) out.push(row("meta", ["key", "value"], ["helpline_name", meta.helpline.name]));
if (meta.helpline?.phone) out.push(row("meta", ["key", "value"], ["helpline_phone", meta.helpline.phone]));
out.push("");

for (const [id, s] of Object.entries(data.stops)) {
  out.push(row("stops", ["id", "name", "area", "lat", "lon"], [id, s.name, s.area ?? "", s.lat ?? null, s.lon ?? null]));
  for (const [kind, key] of [["landmark", "landmarks"], ["tip", "tips"], ["safety", "safety"]]) {
    (s[key] ?? []).forEach((text, i) =>
      out.push(row("stop_notes", ["stop_id", "kind", "position", "text"], [id, kind, i, text])));
  }
}
out.push("");

data.routes.forEach((r, order) => {
  out.push(row("routes",
    ["id", "number", "name", "kind", "headsign_out", "headsign_back", "fare_single_pence", "fare_return_pence", "sort_order"],
    [r.id, r.number, r.name, r.kind ?? "", r.headsign.out, r.headsign.back, pence(r.fare.single), pence(r.fare.return), order]));
  for (const [dir, pattern] of Object.entries(r.patterns)) {
    pattern.forEach((p, i) => {
      if (!data.stops[p.stop]) throw new Error(`Route ${r.id} uses unknown stop ${p.stop}`);
      out.push(row("route_stops", ["route_id", "dir", "position", "stop_id", "offset_min"], [r.id, dir, i, p.stop, p.offset]));
    });
  }
  for (const t of r.trips) {
    for (const d of t.days) {
      for (const time of t.times) {
        out.push(row("trips", ["route_id", "dir", "days", "depart"], [r.id, t.dir, checkDays(d, `route ${r.id}`), time]));
      }
    }
  }
  for (const b of r.busy ?? []) {
    for (const d of b.days) {
      out.push(row("busy_periods", ["route_id", "days", "starts", "ends", "note"], [r.id, checkDays(d, `route ${r.id}`), b.from, b.to, b.note]));
    }
  }
  out.push("");
});

writeFileSync(output, out.join("\n"));
console.log(`Wrote ${output}`);
